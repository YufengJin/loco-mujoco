"""
loco-mujoco RL evaluation: load a saved agent checkpoint and replay it.

Purpose
-------
Loads an RL checkpoint produced by `scripts/train_rl_policy.py` (or the
upstream `examples/training_examples/*/experiment.py` it dispatches to) and
runs deterministic rollouts on the original training env. The repo's
algorithm classes (PPOJax / GAILJax / AMPJax) expose evaluation through
`play_policy(env, agent_conf, agent_state, ...)` — a self-contained batched
rollout. This script is a thin CLI over that method, with mandatory
per-run log persistence so long evals stay auditable when stdout is gone.

Logs land under `<log_dir>/eval/<run_tag>--<YYYYMMDD_HHMMSS>/eval.log`.
The header dumps every parsed argparse arg so a reader six months later can
reproduce the invocation. Checkpoint file pattern: `<ClassName>_saved.pkl`
(e.g. `PPOJax_saved.pkl`).

Example
-------
    # Train a tiny policy first, then evaluate
    python scripts/train_rl_policy.py --algo ppo experiment.total_timesteps=5000
    python scripts/run_eval.py --checkpoint_path outputs/.../PPOJax_saved.pkl \\
        --algo ppo --n-steps 1000 --deterministic

    # Replay on CPU MuJoCo with video recording
    python scripts/run_eval.py --checkpoint_path outputs/.../PPOJax_saved.pkl \\
        --use_mujoco --record --n-steps 500

Generated by benchmark-env-generator (RL Category, dispatcher mode).
"""
import argparse
import atexit
import os
import signal
import sys
from datetime import datetime
from typing import Optional

from omegaconf import OmegaConf

from loco_mujoco import TaskFactory
from loco_mujoco.algorithms import PPOJax, GAILJax, AMPJax


ALGO_CLASS_MAP = {
    "ppo": PPOJax,
    "gail": GAILJax,
    "amp": AMPJax,
    "rl_mimic": PPOJax,  # jax_rl_mimic reuses PPOJax + MimicReward
}


def log(msg: str, log_file: Optional["os.PathLike"] = None) -> None:
    """Print to stdout and, if open, also write to a log file (flushed each call)."""
    print(msg)
    if log_file is not None and not log_file.closed:
        log_file.write(msg + "\n")
        log_file.flush()


def main():
    parser = argparse.ArgumentParser(description="Evaluate an RL checkpoint on its training env.")
    parser.add_argument("--checkpoint_path", required=True,
                        help="Path to saved agent (e.g. PPOJax_saved.pkl)")
    parser.add_argument("--algo", default="ppo", choices=list(ALGO_CLASS_MAP.keys()),
                        help="Algorithm class (determines the save schema). Default: ppo.")
    parser.add_argument("--n-envs", type=int, default=1, help="Parallel rollout envs (default 1)")
    parser.add_argument("--n-steps", type=int, default=1000, help="Total env steps to replay")
    parser.add_argument("--use_mujoco", action="store_true",
                        help="Replay on CPU MuJoCo instead of MJX (forces n_envs=1).")
    parser.add_argument("--record", action="store_true",
                        help="Save an MP4 of the rollout under ./LocoMuJoCo_recordings/")
    parser.add_argument("--deterministic", action="store_true",
                        help="Set log_std=-inf so the policy is deterministic")
    parser.add_argument("--train_state_seed", type=int, default=0,
                        help="Seed index if checkpoint was trained with n_seeds > 1")
    parser.add_argument("--log_dir", type=str, default="./logs",
                        help="Parent dir for per-run eval logs (created if missing)")
    parser.add_argument("--run_tag", type=str, default=None,
                        help="Short tag used for the run directory name (default: env_name)")
    args = parser.parse_args()

    os.environ.setdefault("XLA_FLAGS", "--xla_gpu_triton_gemm_any=True")

    algo_cls = ALGO_CLASS_MAP[args.algo]
    agent_conf, agent_state = algo_cls.load_agent(args.checkpoint_path)
    config = agent_conf.config

    # Reconstruct the original env from the embedded config.
    factory = TaskFactory.get_factory_cls(config.experiment.task_factory.name)
    OmegaConf.set_struct(config, False)
    config.experiment.env_params["headless"] = True
    env = factory.make(**config.experiment.env_params, **config.experiment.task_factory.params)

    env_name = config.experiment.env_params.get("env_name", "env")
    run_tag = args.run_tag or env_name
    date_str = datetime.now().strftime("%Y%m%d_%H%M%S")
    run_dir = os.path.join(args.log_dir, "eval", f"{run_tag}--{date_str}")
    os.makedirs(run_dir, exist_ok=True)
    log_path = os.path.join(run_dir, "eval.log")
    log_file = open(log_path, "w")

    def _cleanup(signum=None, frame=None):
        try:
            if not log_file.closed:
                log_file.close()
        finally:
            sys.stdout.flush()
            sys.stderr.flush()
        if signum is not None:
            os._exit(1)

    signal.signal(signal.SIGINT, _cleanup)
    signal.signal(signal.SIGTERM, _cleanup)
    atexit.register(lambda: None if log_file.closed else log_file.close())

    log("=" * 60, log_file)
    log("loco-mujoco RL eval", log_file)
    log("=" * 60, log_file)
    for k, v in sorted(vars(args).items()):
        log(f"  {k}: {v}", log_file)
    log(f"  env_name: {env_name}", log_file)
    log(f"  task_factory: {config.experiment.task_factory.name}", log_file)
    log(f"  run_dir: {run_dir}", log_file)
    log("=" * 60, log_file)
    log("", log_file)

    try:
        if args.use_mujoco:
            algo_cls.play_policy_mujoco(
                env, agent_conf, agent_state,
                deterministic=args.deterministic,
                n_steps=args.n_steps,
                record=args.record,
                train_state_seed=args.train_state_seed,
            )
        else:
            algo_cls.play_policy(
                env, agent_conf, agent_state,
                deterministic=args.deterministic,
                n_steps=args.n_steps,
                n_envs=args.n_envs,
                record=args.record,
                train_state_seed=args.train_state_seed,
            )

        log("", log_file)
        log("=" * 60, log_file)
        log("FINAL RESULTS", log_file)
        log("=" * 60, log_file)
        log(f"  checkpoint:  {args.checkpoint_path}", log_file)
        log(f"  algo:        {args.algo}", log_file)
        log(f"  env_name:    {env_name}", log_file)
        log(f"  n_envs:      {args.n_envs}", log_file)
        log(f"  n_steps:     {args.n_steps}", log_file)
        log(f"  log_file:    {log_path}", log_file)
        log("=" * 60, log_file)
    finally:
        if not log_file.closed:
            log_file.close()


if __name__ == "__main__":
    main()
